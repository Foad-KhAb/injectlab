"""Audit a saved experiment and write supplementary report tables without rerunning models."""

import hashlib
import json
from collections import Counter
from pathlib import Path

from injectlab.eval import metrics
from injectlab.eval.config import expand, load_config
from injectlab.eval.runner import load_rows


def main() -> None:
    config = load_config(Path("configs/full.yaml"))
    path = config.results_path
    rows = load_rows(path)
    latest = {r.run_id: r for r in rows}
    expected = {s.run_id for s in expand(config)}
    if set(latest) != expected or any(r.error for r in latest.values()):
        raise SystemExit("Report audit requires all configured episodes with no unresolved errors.")
    frame = metrics.to_frame(rows)
    policy_counts = []
    outcomes = []
    for defense, group in frame.groupby("defense", sort=True):
        old = group.response_policy.isna()
        policy_counts.append(
            {"defense": defense, "legacy": int(old.sum()), "streaming": int((~old).sum())}
        )
        benign, attacked = group[~group.is_attack], group[group.is_attack]
        outcomes.append(
            {
                "defense": defense,
                "benign_success": int(benign.user_task_success.sum()),
                "benign_n": len(benign),
                "attacked_success": int(attacked.user_task_success.sum()),
                "attack_success": int(attacked.attack_success.sum()),
                "attacked_n": len(attacked),
                "both_success": int((attacked.user_task_success & attacked.attack_success).sum()),
            }
        )
    comparisons = []
    for rec in metrics.compare_defenses(frame).to_dict("records"):
        comparisons.append(
            {
                "defense": rec["defense"],
                "metric": rec["metric"],
                "only_baseline": rec["only_a"],
                "only_defense": rec["only_b"],
                "p": metrics.exact_mcnemar(rec["only_a"], rec["only_b"]),
            }
        )
    # Descriptive subset only: retain task/attack pairs where both clients used the old
    # response policy. This is not a new balanced experiment or an additional hypothesis test.
    keys = ["model", "user_task", "injection_task", "attack_template", "slot", "seed"]
    attacked = frame[frame.is_attack]
    baseline = attacked[attacked.defense == "none"]
    subsets = []
    for defense in ["delimiting", "sandwich"]:
        other = attacked[(attacked.defense == defense) & attacked.response_policy.isna()]
        pairs = baseline.merge(other, on=keys, suffixes=("_baseline", "_defense"))
        subsets.append(
            {
                "defense": defense,
                "n": len(pairs),
                "baseline_asr_k": int(pairs.attack_success_baseline.sum()),
                "defense_asr_k": int(pairs.attack_success_defense.sum()),
                "baseline_utility_k": int(pairs.user_task_success_baseline.sum()),
                "defense_utility_k": int(pairs.user_task_success_defense.sum()),
            }
        )
    detector = frame[frame.defense == "detector"]
    benign_detector = detector[~detector.is_attack]
    audit = {
        "results_path": str(path),
        "results_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "raw_rows": len(rows),
        "unique_episodes": len(latest),
        "raw_errors": sum(r.error is not None for r in rows),
        "unresolved_errors": 0,
        "extra_success_rows": sum(r.error is None for r in rows) - len(latest),
        "recorded_commits": dict(Counter(r.git_commit for r in rows)),
        "first_timestamp": min(r.timestamp for r in rows),
        "last_timestamp": max(r.timestamp for r in rows),
        "errors": dict(Counter((r.error or "").splitlines()[0] for r in rows if r.error)),
        "policy_counts": policy_counts,
        "outcomes": outcomes,
        "defense_comparisons": comparisons,
        "legacy_policy_subsets": subsets,
        "detector_benign_redactions": int(benign_detector.redacted_outputs.sum()),
        "detector_benign_outputs": int(benign_detector.num_tool_outputs.sum()),
        "detector_attacked_flagged": int((detector[detector.is_attack].redacted_outputs > 0).sum()),
    }
    out = Path("figures")
    out.mkdir(exist_ok=True)
    (out / "run_audit.json").write_text(json.dumps(audit, indent=2) + "\n", encoding="utf-8")
    lines = [
        "# Run audit",
        "",
        "Generated by `python scripts/report_audit.py` from saved results.",
        "No model requests are made.",
        "",
        "## Completeness",
        "",
        f"- Raw rows: {audit['raw_rows']}; unique episode settings: {len(latest)}.",
        f"- Historical error rows: {audit['raw_errors']}; unresolved errors: 0.",
        f"- Extra successful row from duplicate execution: {audit['extra_success_rows']}.",
        f"- Recorded code labels: {audit['recorded_commits']}.",
        f"- Row timestamps: {audit['first_timestamp']} to {audit['last_timestamp']}.",
        f"- Results SHA-256: `{audit['results_sha256']}`.",
        "",
        "## Generation policy by defense",
        "",
        "Legacy means the limit and streaming policy were not recorded in that row.",
        "",
        "| Defense | Legacy episodes | 512-token streaming episodes |",
        "| --- | ---: | ---: |",
    ]
    lines += [f"| {r['defense']} | {r['legacy']} | {r['streaming']} |" for r in policy_counts]
    lines += [
        "",
        "## Exact outcome counts",
        "",
        "| Defense | Benign utility | Utility under attack | Attack success | Both successes |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    lines += [
        f"| {r['defense']} | {r['benign_success']}/{r['benign_n']} | "
        f"{r['attacked_success']}/{r['attacked_n']} | {r['attack_success']}/{r['attacked_n']} | "
        f"{r['both_success']} |"
        for r in outcomes
    ]
    lines += [
        "",
        "## Unrounded exact McNemar p-values",
        "",
        "Eight defense comparisons; report applies Bonferroni across these "
        "and five language tests.",
        "Generation-policy confounding still limits causal interpretation.",
        "",
        "| Defense | Metric | Only baseline | Only defense | p |",
        "| --- | --- | ---: | ---: | ---: |",
    ]
    lines += [
        f"| {r['defense']} | {r['metric']} | {r['only_baseline']} | {r['only_defense']} | "
        f"{r['p']:.8g} |"
        for r in comparisons
    ]
    lines += [
        "",
        "## Shared legacy-policy subsets (descriptive)",
        "",
        "| Defense | Paired n | Baseline ASR | Defense ASR | "
        "Baseline utility under attack | Defense utility under attack |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    lines += [
        f"| {r['defense']} | {r['n']} | {r['baseline_asr_k']}/{r['n']} | "
        f"{r['defense_asr_k']}/{r['n']} | {r['baseline_utility_k']}/{r['n']} | "
        f"{r['defense_utility_k']}/{r['n']} |"
        for r in subsets
    ]
    lines += [
        "",
        "## Detector denominators",
        "",
        f"- Benign redactions: {audit['detector_benign_redactions']}/"
        f"{audit['detector_benign_outputs']} tool outputs.",
        f"- Attacked episodes with any redaction: {audit['detector_attacked_flagged']}/250.",
        "",
    ]
    (out / "run_audit.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Audited {len(latest)} complete episodes; wrote {out}/run_audit.md and run_audit.json")


if __name__ == "__main__":
    main()
